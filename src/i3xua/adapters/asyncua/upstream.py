# Variable metadata batch: one multi-attr `Read` covering DataType plus the
# five attributes tag-heavy SCADA servers reliably populate. Order matters —
# `_decode_metadata_results` unwinds in the same (var-major, attr-minor)
# layout that `_build_metadata_read_items` produces.
_METADATA_ATTRS: tuple[Any, ...] = (
    ua.AttributeIds.DataType,
    ua.AttributeIds.ValueRank,
    ua.AttributeIds.ArrayDimensions,
    ua.AttributeIds.AccessLevel,
    ua.AttributeIds.UserAccessLevel,
    ua.AttributeIds.MinimumSamplingInterval,
    ua.AttributeIds.Historizing,
)
_METADATA_ATTR_NAMES: tuple[str, ...] = (
    "data_type_node_id",
    "value_rank",
    "array_dimensions",
    "access_level",
    "user_access_level",
    "minimum_sampling_interval",
    "historizing",
)


def _build_metadata_read_items(var_nodes: list[ua.NodeId]) -> list[ua.ReadValueId]:
    """One ReadValueId per (variable x attribute) pair, ordered (var-major,
    attr-minor) to match `_decode_metadata_results`."""
    return [
        ua.ReadValueId(NodeId_=v, AttributeId=attr) for v in var_nodes for attr in _METADATA_ATTRS
    ]


def _decode_metadata_results(
    items: list[ua.ReadValueId], results: list[ua.DataValue]
) -> dict[str, dict[str, Any]]:
    """Group results back per variable, keyed by NodeId.to_string().

    ``BadAttributeIdInvalid`` (and any other Bad status) becomes None for
    that field. ``data_type_node_id`` is stringified to canonical OPC UA
    form; ``array_dimensions`` becomes a tuple (or None when the server
    returns an empty list, which is what scalars produce).
    """
    n = len(_METADATA_ATTRS)
    out: dict[str, dict[str, Any]] = {}
    for v_idx in range(0, len(items), n):
        var_node_id = items[v_idx].NodeId.to_string()
        per_var: dict[str, Any] = {}
        for attr_idx, attr_name in enumerate(_METADATA_ATTR_NAMES):
            dv = results[v_idx + attr_idx]
            sc = dv.StatusCode_ if hasattr(dv, "StatusCode_") else dv.StatusCode
            ok = sc.is_good() if hasattr(sc, "is_good") else (getattr(sc, "value", 0) == 0)
            if not ok or dv.Value is None:
                per_var[attr_name] = None
                continue
            val = dv.Value.Value
            if val is None:
                per_var[attr_name] = None
            elif attr_name == "data_type_node_id":
                per_var[attr_name] = val.to_string()
            elif attr_name == "array_dimensions":
                per_var[attr_name] = tuple(val) if val else None
            else:
                per_var[attr_name] = val
        out[var_node_id] = per_var
    return out


_MODE_BY_NAME: dict[str, ua.MessageSecurityMode] = {
    "None": ua.MessageSecurityMode.None_,
    "Sign": ua.MessageSecurityMode.Sign,
    "SignAndEncrypt": ua.MessageSecurityMode.SignAndEncrypt,
}


def _resolve_endpoint_and_trust(
    endpoints: list[Any], cfg: ConnectionConfig
) -> tuple[str, Path | None]:
    """Pick the endpoint matching channel.policy + channel.mode; for
    ChannelSigned, also resolve the server cert.

    When `channel.server_trust_list_dir` is set: SHA-256-match the discovered
    `ServerCertificate` against the directory, refuse-on-no-match.
    When omitted: the discovered cert IS the identity. We persist it to a
    per-connection cache directory (`<tempdir>/i3xua-trust/<connection>/`)
    on first sight and reuse it on reconnect; the path is what gets passed
    into `set_security_string`.

    Returns (ApplicationUri, resolved_server_cert_path | None).
    """
    channel = cfg.channel
    mode = _MODE_BY_NAME[channel.mode]
    match = pick_matching_endpoint(endpoints, policy=channel.policy, mode=mode)
    if match is None:
        raise RuntimeError(
            f"no endpoint on {cfg.endpoint!r} matches "
            f"policy={channel.policy!r} mode={channel.mode!r}"
        )
    if isinstance(channel, ChannelNone):
        return match.Server.ApplicationUri, None
    assert isinstance(channel, ChannelSigned)

    if channel.server_trust_list_dir is not None:
        resolved = resolve_server_cert(
            server_cert_der=match.ServerCertificate,
            trust_dir=channel.server_trust_list_dir,
        )
    else:
        resolved = _autotrust_server_cert(cfg.name, match.ServerCertificate)
        logger.info(
            "auto-trusted discovered server cert for %s (no server_trust_list_dir "
            "configured); cached at %s",
            cfg.name,
            resolved,
        )
    return match.Server.ApplicationUri, resolved


def _autotrust_server_cert(connection_name: str, server_cert_der: bytes) -> Path:
    """Persist the discovered ServerCertificate into a per-connection cache
    directory and return the file path.

    Used when `channel.server_trust_list_dir` is omitted — the cert returned
    during endpoint discovery is treated as the server's identity. Writes are
    idempotent: on subsequent connects the same file is overwritten with the
    same bytes.
    """
    cache_dir = Path(tempfile.gettempdir()) / "i3xua-trust" / connection_name
    cache_dir.mkdir(parents=True, exist_ok=True)
    out = cache_dir / "server.der"
    out.write_bytes(server_cert_der)
    return out


def _ua_node_id(node_id_str: str) -> ua.NodeId:
    return ua.NodeId.from_string(node_id_str)


_NC_FROM_INT: dict[int, NodeClass] = {
    1: NodeClass.Object,
    2: NodeClass.Variable,
    4: NodeClass.Method,
    8: NodeClass.ObjectType,
    16: NodeClass.VariableType,
    32: NodeClass.ReferenceType,
    64: NodeClass.DataType,
    128: NodeClass.View,
}


def _node_class_from_ua(value: Any) -> NodeClass:
    # read_attributes returns raw int; per-node read returns ua.NodeClass enum.
    if isinstance(value, int) and not hasattr(value, "name"):
        return _NC_FROM_INT.get(value, NodeClass.Object)
    try:
        name = value.name if hasattr(value, "name") else str(value)
    except Exception:
        name = "Object"
    try:
        return NodeClass(name)
    except ValueError:
        return NodeClass.Object


def _is_null_node_id(node_id: Any) -> bool:
    """asyncua returns NodeId(Identifier=0, NamespaceIndex=0) for unset
    TypeDefinition fields. Treat that as 'no type definition'."""
    try:
        return bool(node_id.Identifier == 0 and node_id.NamespaceIndex == 0)
    except AttributeError:
        return False


# Module-level alias used by the lifted helper methods (_follow_continuations, _retry_starved).
_BAD_NO_CP_STATUS = ua.StatusCodes.BadNoContinuationPoints

