class _Registries:
    """Holds the three registries + subscription manager + history on the main
    loop. Methods are coroutines intended to be scheduled from worker threads
    via `run_coroutine_threadsafe`."""

    def __init__(
        self,
        *,
        namespaces: NamespaceRegistry,
        types: TypeRegistry,
        instances: InstanceRegistry,
        subscriptions: SubscriptionManager,
        history: HistoryStore,
        browse_metrics: dict[str, dict[str, Any]] | None = None,
    ) -> None:
        self.namespaces = namespaces
        self.types = types
        self.instances = instances
        self.subscriptions = subscriptions
        self.history = history
        # Per-connection browse-phase timings, populated on each successful
        # (re)connect. Surfaced via /admin/state so operators can see how
        # long initial browse takes against a given OPC UA server.
        self.browse_metrics: dict[str, dict[str, Any]] = (
            browse_metrics if browse_metrics is not None else {}
        )

    async def apply_snapshot(
        self,
        connection: str,
        namespace_infos: list[NamespaceInfo],
        browse_result: BrowseResult,
        *,
        application_uri: str | None = None,
    ) -> None:
        # Namespaces. Only reconcile entries owned by this connection; others
        # (e.g. from a second server) remain untouched.
        current = self.namespaces.snapshot()
        keep_other_conns = [ni for ni in current.values() if ni.connection != connection]
        await self.namespaces.reconcile(keep_other_conns + namespace_infos)

        # Types: rebuild entries for this connection only. No custom Pydantic
        # models yet — ship an identity placeholder so the registry wiring works.

        # TypeRegistry has no per-connection reconcile; we compose the desired
        # set by filtering the current view.
        all_types = list(self.types.by_hash().values())
        keep = [rt for rt in all_types if rt.descriptor.connection != connection]
        desired = list(browse_result.types)
        # Clear & rewrite atomically.
        self.types._by_hash = {}
        self.types._by_source = {}
        for rt in keep:
            self.types._by_hash[rt.descriptor.structural_hash] = rt
            self.types._by_source[
                ElementRef(rt.descriptor.connection, rt.descriptor.source_node_id).as_id()
            ] = rt.descriptor.structural_hash

        for desc in desired:
            self.types._by_hash[desc.structural_hash] = RegisteredType(
                descriptor=desc,
                model=_build_pydantic_model(desc),
            )
            self.types._by_source[ElementRef(desc.connection, desc.source_node_id).as_id()] = (
                desc.structural_hash
            )

        # / CESMII RFC §3.3: every i3X deployment MUST carry an
        # `UnknownType` placeholder so instances whose TypeDefinition couldn't
        # be resolved (typically Methods in OPC UA, or any node reached without
        # a HasTypeDefinition edge) still carry a valid `typeId`. We register
        # one per connection so the ObjectType shows up in `/objecttypes`
        # alongside real types.
        unknown = TypeDescriptor(
            source_node_id="UnknownType",
            display_name="UnknownType",
            namespace_uri="urn:cesmii:i3x:placeholder",
            connection=connection,
            structural_hash=f"unknown-type-{connection}",
            json_schema={
                "type": "object",
                "description": (
                    "CESMII RFC §3.3 placeholder for instances whose source "
                    "type could not be resolved during browse."
                ),
            },
            version=None,
            application_uri=application_uri,
        )
        self.types._by_hash[unknown.structural_hash] = RegisteredType(
            descriptor=unknown,
            model=_build_pydantic_model(unknown),
        )
        self.types._by_source[ElementRef(unknown.connection, unknown.source_node_id).as_id()] = (
            unknown.structural_hash
        )

        # Instances: same per-connection semantics.
        all_instances = list(self.instances.snapshot().values())
        retained = [n for n in all_instances if n.connection != connection]
        await self.instances.reconcile(retained + list(browse_result.nodes))

    async def fan_out(self, sample: ValueSample) -> None:
        await self.subscriptions.push(sample)
        await self.history.append(sample)

    async def wanted_node_ids(self, connection: str) -> list[str]:
        """return raw NodeIds (no connection prefix) that some live i3X
        subscription currently has registered for `connection`.

        `_ConnectionBinding._on_connected` uses this to restore server-side
        MonitoredItems after a reconnect without consulting the adapter's
        own bookkeeping (which was cleared on disconnect)."""
        out: set[str] = set()
        for sub_id in await self.subscriptions.list_ids():
            elements = await self.subscriptions.get_elements(sub_id)
            for eid in elements:
                try:
                    ref = ElementRef.parse(eid)
                except ValueError:
                    continue
                if ref.connection == connection:
                    out.add(ref.node_id)
        return sorted(out)


