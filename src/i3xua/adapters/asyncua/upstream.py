@dataclass
class _BrowseCounters:
    """Per-browse-run counters for continuation-point health.

    Surfaced via `browse_metrics[connection]` at end of `_on_connected`.

    Note: `browse_initial_calls` is incremented once per `_batch_browse_*`
    invocation. `browse_children` bumps it twice per batch (once for the
    hier browse, once for the typedef browse). Use this as the denominator
    for `browse_initial_starved` rate calculations.
    """

    browse_initial_calls: int = 0
    browse_initial_starved: int = 0
    browse_initial_starved_recovered: int = 0
    browse_initial_starved_unrecoverable: int = 0
    browse_next_calls: int = 0
    browse_next_starved: int = 0
    browse_next_other_bad: int = 0
    browse_next_starvation_logs_emitted: int = 0  # capped log counter
    browse_children_parent_bad_status: int = 0

    def as_metrics(self) -> dict[str, int]:
        return {
            "browse_children_parent_bad_status": self.browse_children_parent_bad_status,
            "browse_initial_calls": self.browse_initial_calls,
            "browse_initial_starved": self.browse_initial_starved,
            "browse_initial_starved_recovered": self.browse_initial_starved_recovered,
            "browse_initial_starved_unrecoverable": self.browse_initial_starved_unrecoverable,
            "browse_next_calls": self.browse_next_calls,
            "browse_next_starved": self.browse_next_starved,
            "browse_next_other_bad": self.browse_next_other_bad,
            "subtrees_dropped_silently": (self.browse_next_starved + self.browse_next_other_bad),
        }


class _AsyncuaBrowseSource(BrowseSource):
    """Adapts a live `asyncua.Client` to the browse Protocol.

    Intentionally defensive: any asyncua error on a specific node returns
    `None` from `get_node_info`/`get_type_info` so the walk keeps going.
    """

    def __init__(self, client: UaClientLike) -> None:
        self._client: Any = client  # asyncua.Client at runtime
        self.counters: _BrowseCounters = _BrowseCounters()
        # Captured during _pre_connect from the chosen EndpointDescription;
        # surfaced to the browse layer for the wrapper-cast namespace.
        self.application_uri: str | None = None
        self.application_name: str | None = None

    async def get_namespace_array(self) -> list[str]:
        return list(await self._client.get_namespace_array())

    async def get_application_uri(self) -> str | None:
        return self.application_uri

    async def get_application_name(self) -> str | None:
        return self.application_name

    async def _follow_continuations(self, results: list[Any], source_descs: list[Any]) -> None:
        """Drain every ContinuationPoint via BrowseNext and append the
        trailing References onto the matching first-batch result.

        Servers with high fan-out folders return ~1000 refs per node plus
        a ContinuationPoint that must be followed to retrieve the rest.
        Without this, large namespaces are silently truncated.

        Counters: every BrowseNext result is counted; per-result
        StatusCode bumps ``browse_next_starved`` (BadNoContinuationPoints)
        or ``browse_next_other_bad`` (any other non-Good). The first 10
        starvations are logged at WARNING with the originating NodeId.
        ``source_descs`` is the BrowseDescription list whose indices align
        with ``results``; it differs between the hier and typedef paths.

        Wire-protocol detail: asyncua's ``browse_next`` expects a
        ``BrowseNextParameters`` struct, not a bare list of CPs. Passing a
        list silently corrupts the request encoding and leaves
        ``browse_next_calls=0`` in metrics.
        """
        pending: list[tuple[int, bytes]] = [
            (i, r.ContinuationPoint) for i, r in enumerate(results) if r.ContinuationPoint
        ]
        while pending:
            cps = [cp for _, cp in pending]
            bn_params = ua.BrowseNextParameters()
            bn_params.ContinuationPoints = cps
            bn_params.ReleaseContinuationPoints = False
            next_results = await self._client.uaclient.browse_next(bn_params)
            new_pending: list[tuple[int, bytes]] = []
            for (orig_idx, _old_cp), nr in zip(pending, next_results, strict=True):
                self.counters.browse_next_calls += 1
                status_value = nr.StatusCode.value if nr.StatusCode is not None else 0
                if status_value == int(_BAD_NO_CP_STATUS):
                    self.counters.browse_next_starved += 1
                    if self.counters.browse_next_starvation_logs_emitted < 10:
                        self.counters.browse_next_starvation_logs_emitted += 1
                        logger.warning(
                            "browse_next: BadNoContinuationPoints on node %s "
                            "(remaining children silently lost; counters captured)",
                            source_descs[orig_idx].NodeId.to_string(),
                        )
                elif not nr.StatusCode.is_good():
                    self.counters.browse_next_other_bad += 1
                results[orig_idx].References.extend(nr.References or [])
                if nr.ContinuationPoint:
                    new_pending.append((orig_idx, nr.ContinuationPoint))
            pending = new_pending

    async def _retry_starved(
        self, browse_params: Any, descs_list: list[Any], results: list[Any]
    ) -> None:
        """Re-issue browses for any result that came back
        BadNoContinuationPoints — servers truncate with that status when
        their session-level CP pool is exhausted. Each retry runs SOLO so
        the freed CP is guaranteed available, and the result slot is
        overwritten in place.
        """
        starved: list[int] = [
            i for i, r in enumerate(results) if r.StatusCode.value == int(_BAD_NO_CP_STATUS)
        ]
        self.counters.browse_initial_starved += len(starved)
        while starved:
            idx = starved.pop()
            solo_params = ua.BrowseParameters()
            solo_params.View.Timestamp = ua.get_win_epoch()
            solo_params.RequestedMaxReferencesPerNode = browse_params.RequestedMaxReferencesPerNode
            solo_params.NodesToBrowse = [descs_list[idx]]
            solo = await self._client.uaclient.browse(solo_params)
            await self._follow_continuations(solo, [descs_list[idx]])
            if solo and solo[0].StatusCode.value == int(_BAD_NO_CP_STATUS):
                # Server still can't issue a CP even for one node;
                # log and accept the partial result.
                self.counters.browse_initial_starved_unrecoverable += 1
                logger.warning(
                    "browse: BadNoContinuationPoints persists on %s "
                    "even with batch=1; partial result kept",
                    descs_list[idx].NodeId.to_string(),
                )
                continue
            if not solo:
                self.counters.browse_initial_starved_unrecoverable += 1
                logger.warning(
                    "browse: solo retry for %s returned empty result; treating as unrecoverable",
                    descs_list[idx].NodeId.to_string(),
                )
                continue
            self.counters.browse_initial_starved_recovered += 1
            results[idx] = solo[0]

    async def get_node_info(self, node_id: str) -> NodeInfo | None:
        try:
            node = self._client.get_node(_ua_node_id(node_id))

            # perf: pipeline all independent reads via asyncio.gather
            # so they share one SecureChannel round-trip window instead of
            # serializing 6 sequential request/response pairs per node.
            browse_name_f = node.read_browse_name()
            display_name_f = node.read_display_name()
            node_class_f = node.read_node_class()
            hier_refs_f = node.get_references(
                refs=ua.NodeId(33, 0),  # HierarchicalReferences
                direction=ua.BrowseDirection.Forward,
                includesubtypes=True,
            )
            type_def_refs_f = node.get_references(
                refs=ua.NodeId(40, 0),  # HasTypeDefinition
                direction=ua.BrowseDirection.Forward,
            )

            results = await asyncio.gather(
                browse_name_f,
                display_name_f,
                node_class_f,
                hier_refs_f,
                type_def_refs_f,
                return_exceptions=True,
            )

            # Unpack — any individual failure is tolerated.
            for r in results[:3]:
                if isinstance(r, BaseException):
                    return None
            browse_name: Any = results[0]
            display_name: Any = results[1]
            node_class: Any = results[2]
            hier_refs: Any = results[3] if not isinstance(results[3], BaseException) else []
            type_def_refs: Any = results[4] if not isinstance(results[4], BaseException) else []

            refs_out: list[tuple[str, str]] = [
                (ref.ReferenceTypeId.to_string(), ref.NodeId.to_string()) for ref in hier_refs
            ]

            type_def_id: str | None = None
            if type_def_refs:
                type_def_id = type_def_refs[0].NodeId.to_string()

            data_type: str | None = None
            if _node_class_from_ua(node_class) is NodeClass.Variable:
                try:
                    dt = await node.read_data_type()
                    data_type = dt.to_string()
                except Exception:
                    data_type = None

            namespace_index = _ua_node_id(node_id).NamespaceIndex
            ns_array = await self._client.get_namespace_array()
            namespace_uri = ns_array[namespace_index] if namespace_index < len(ns_array) else ""

            return NodeInfo(
                node_id=node_id,
                browse_name=str(browse_name.Name),
                display_name=str(display_name.Text),
                node_class=_node_class_from_ua(node_class),
                namespace_uri=namespace_uri,
                data_type_node_id=data_type,
                type_definition_node_id=type_def_id,
                parent_node_id=None,
                hierarchical_refs=tuple(refs_out),
                has_component_children=any(ref[0] in HAS_COMPONENT_REFS for ref in refs_out),
            )
        except Exception as exc:
            logger.debug("get_node_info(%s) failed: %s", node_id, exc)
            return None

    async def get_node_info_batch(self, node_ids: list[str]) -> list[NodeInfo | None]:
        """Used only for BFS roots (1-3 NodeIds, off the hot path).
        Wraps per-node get_node_info — optimization here is unnecessary."""
        return [await self.get_node_info(nid) for nid in node_ids]

    async def browse_children(self, parent_node_ids: list[str]) -> list[BrowsedChild]:
        """One batched Browse(HierarchicalReferences, ResultMask=All) for
        the given parents, drain CPs, recover starved, then one batched
        DataType read for any Variable children. Return flat list of
        BrowsedChild across all parents (interleaved by parent index)."""
        if not parent_node_ids:
            return []

        nodes = [self._client.get_node(_ua_node_id(nid)) for nid in parent_node_ids]
        descs: list[Any] = []
        for n in nodes:
            d = ua.BrowseDescription()
            d.NodeId = n.nodeid
            d.BrowseDirection = ua.BrowseDirection.Forward
            d.ReferenceTypeId = ua.NodeId(33, 0)  # HierarchicalReferences
            d.IncludeSubtypes = True
            d.NodeClassMask = 0
            d.ResultMask = ua.BrowseResultMask.All
            descs.append(d)

        params = ua.BrowseParameters()
        params.View.Timestamp = ua.get_win_epoch()
        params.RequestedMaxReferencesPerNode = 0  # server decides
        params.NodesToBrowse = descs

        self.counters.browse_initial_calls += 1
        try:
            results = await self._client.uaclient.browse(params)
        except Exception as exc:
            logger.warning(
                "browse_children: initial Browse failed (%d parents): %s",
                len(parent_node_ids),
                exc,
            )
            return []

        await self._follow_continuations(results, descs)
        await self._retry_starved(params, descs, results)

        ns_array = await self._client.get_namespace_array()

        children: list[BrowsedChild] = []
        variable_children: list[int] = []  # indices into `children`

        for parent_idx, result in enumerate(results):
            parent_nid = parent_node_ids[parent_idx]
            if not result.StatusCode.is_good():
                # Per-parent failure (e.g. BadNodeIdUnknown after retry).
                # Skip; walker treats this as "no children." Counter
                # surfaces the rate via /admin/state — same convention
                # as browse_initial_starved/browse_next_starved.
                self.counters.browse_children_parent_bad_status += 1
                continue
            for ref in result.References or []:
                child_nid = ref.NodeId.to_string()
                ns_idx = ref.NodeId.NamespaceIndex
                ns_uri = ns_array[ns_idx] if 0 <= ns_idx < len(ns_array) else ""
                nc = _node_class_from_ua(ref.NodeClass)
                type_def = (
                    ref.TypeDefinition.to_string()
                    if ref.TypeDefinition is not None and not _is_null_node_id(ref.TypeDefinition)
                    else None
                )
                browse_name = (
                    str(ref.BrowseName.Name)
                    if hasattr(ref.BrowseName, "Name")
                    else str(ref.BrowseName)
                )
                display_name = (
                    str(ref.DisplayName.Text)
                    if hasattr(ref.DisplayName, "Text")
                    else str(ref.DisplayName)
                )
                info = NodeInfo(
                    node_id=child_nid,
                    browse_name=browse_name,
                    display_name=display_name,
                    node_class=nc,
                    namespace_uri=ns_uri,
                    type_definition_node_id=type_def,
                    data_type_node_id=None,  # filled below for Variables
                    parent_node_id=parent_nid,
                    hierarchical_refs=(),  # not needed; walker uses parent linkage
                    has_component_children=False,  # finalized post-walk
                )
                idx = len(children)
                children.append(
                    BrowsedChild(
                        info=info,
                        parent_node_id=parent_nid,
                        parent_relationship=RELATIONSHIP_NAMES.get(
                            ref.ReferenceTypeId.to_string(), ""
                        ),
                    )
                )
                if nc is NodeClass.Variable:
                    variable_children.append(idx)

        if variable_children:
            # Single multi-attribute Read instead of N single-attr reads.
            # Seven attributes per Variable (DataType + six metadata fields).
            # Bad statuses on individual attributes become None on the
            # NodeInfo; a Read-call-level exception still degrades silently.
            var_node_ids = [_ua_node_id(children[i].info.node_id) for i in variable_children]
            items = _build_metadata_read_items(var_node_ids)
            try:
                results = await self._client.uaclient.read(ua.ReadParameters(NodesToRead=items))
            except Exception as exc:
                logger.debug(
                    "browse_children: metadata Read for %d Variable children failed: %s",
                    len(var_node_ids),
                    exc,
                )
                return children
            metadata_by_node = _decode_metadata_results(items, results)
            for idx, var_nid in zip(variable_children, var_node_ids, strict=True):
                attrs = metadata_by_node.get(var_nid.to_string(), {})
                old = children[idx]
                children[idx] = replace(
                    old,
                    info=replace(
                        old.info,
                        data_type_node_id=attrs.get("data_type_node_id"),
                        value_rank=attrs.get("value_rank"),
                        array_dimensions=attrs.get("array_dimensions"),
                        access_level=attrs.get("access_level"),
                        user_access_level=attrs.get("user_access_level"),
                        minimum_sampling_interval=attrs.get("minimum_sampling_interval"),
                        historizing=attrs.get("historizing"),
                    ),
                )

        return children

    async def get_type_info(self, node_id: str) -> TypeInfo | None:
        """Return a `TypeInfo` with REAL InstanceDeclarations.

        For each `HasComponent` / `HasProperty` child of the ObjectType, read
        its `ModellingRule` (`Mandatory` -> `is_optional=False`, `Optional` ->
        True; placeholders covered too), its DataType NodeId, and ValueRank.
        Children without a ModellingRule are skipped (they're helpers, not
        InstanceDeclarations).
        """
        try:
            node = self._client.get_node(_ua_node_id(node_id))
            display_name = await node.read_display_name()

            # Detect VariableType vs ObjectType to decide whether to read DataType.
            try:
                node_class = await node.read_node_class()
            except Exception:
                node_class = ua.NodeClass.ObjectType  # safe default

            data_type_node_id: str | None = None
            if node_class == ua.NodeClass.VariableType:
                try:
                    dt = await node.read_data_type()
                    data_type_node_id = dt.to_string()
                except Exception as exc:
                    logger.debug("read_data_type(%s) failed: %s", node_id, exc)

            subtype_refs = await node.get_references(
                refs=ua.NodeId(45, 0),  # HasSubtype
                direction=ua.BrowseDirection.Forward,
            )
            subtypes = tuple(ref.NodeId.to_string() for ref in subtype_refs)

            namespace_index = _ua_node_id(node_id).NamespaceIndex
            ns_array = await self._client.get_namespace_array()
            namespace_uri = ns_array[namespace_index] if namespace_index < len(ns_array) else ""

            child_refs = []
            for ref_type_id in (ua.NodeId(47, 0), ua.NodeId(46, 0)):  # HasComponent, HasProperty
                try:
                    refs = await node.get_references(
                        refs=ref_type_id, direction=ua.BrowseDirection.Forward
                    )
                    child_refs.extend(refs)
                except Exception as exc:
                    logger.debug(
                        "get_references(%s, %s) failed: %s",
                        node_id,
                        ref_type_id.to_string(),
                        exc,
                    )

            fields: list[InstanceDeclaration] = []
            seen: set[str] = set()
            for ref in child_refs:
                child_id = ref.NodeId.to_string()
                if child_id in seen:
                    continue
                seen.add(child_id)
                child = self._client.get_node(ref.NodeId)
                try:
                    modelling_rule = await self._read_modelling_rule(child)
                except Exception:
                    modelling_rule = None
                if modelling_rule is None:
                    continue
                try:
                    cbn = await child.read_browse_name()
                    cdt = await child.read_data_type()
                    crank = await self._read_value_rank_safe(child)
                except Exception as exc:
                    logger.debug("InstanceDeclaration read failed on %s: %s", child_id, exc)
                    continue
                fields.append(
                    InstanceDeclaration(
                        name=str(cbn.Name),
                        data_type_node_id=cdt.to_string(),
                        value_rank=crank,
                        is_optional=modelling_rule in {"Optional", "OptionalPlaceholder"},
                    )
                )

            return TypeInfo(
                node_id=node_id,
                display_name=str(display_name.Text),
                namespace_uri=namespace_uri,
                fields=tuple(fields),
                subtypes=subtypes,
                data_type_node_id=data_type_node_id,
            )
        except Exception as exc:
            logger.debug("get_type_info(%s) failed: %s", node_id, exc)
            return None

    @staticmethod
    async def _read_modelling_rule(child: Any) -> str | None:
        """Return the DisplayName of the ModellingRule target
        (`Mandatory` / `Optional` / `MandatoryPlaceholder` / `OptionalPlaceholder`),
        or None if the child has no `HasModellingRule` reference."""
        try:
            refs = await child.get_references(
                refs=ua.NodeId(37, 0),  # HasModellingRule
                direction=ua.BrowseDirection.Forward,
            )
        except Exception:
            return None
        if not refs:
            return None
        return str(refs[0].DisplayName.Text)

    @staticmethod
    async def _read_value_rank_safe(child: Any) -> int:
        try:
            rank = await child.read_attribute(ua.AttributeIds.ValueRank)
            return int(rank.Value.Value)
        except Exception:
            return -1


