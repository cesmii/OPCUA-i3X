class _ConnectionBinding:
    """Owns one `AsyncuaConnection` on a worker thread loop plus its shared
    asyncua Subscription. All public entrypoints are coroutines and must be
    invoked via `ThreadPool.run_on(cfg.name, ...)`."""

    def __init__(
        self,
        cfg: ConnectionConfig,
        pool: ThreadPool,
        main_loop: asyncio.AbstractEventLoop,
        registries: _Registries,
    ) -> None:
        self.cfg = cfg
        self.pool = pool
        self.main_loop = main_loop
        self.registries = registries
        self.conn = AsyncuaConnection(
            cfg,
            # asyncua's Client defaults: timeout=4s, watchdog_intervall=1.0s.
            # 4s is too tight for tag-heavy servers handling batched
            # read_attributes(DataType) against ~50K Variable NodeIds at
            # once — slow servers need >5s to parse and respond, the
            # watchdog times out, asyncua tears down the SecureChannel
            # mid-browse, and the walker silently truncates. 60s request
            # timeout gives ample headroom; watchdog interval stays at 1s
            # so disconnects are still detected promptly.
            client_factory=lambda endpoint: _UriAwareClient(url=endpoint, timeout=60),
            load_enums=load_enums,
        )
        self.conn.on_connected = self._on_connected
        self.conn.on_disconnected = self._on_disconnected
        self.conn.on_pre_connect = self._pre_connect
        # auto-tier state: one asyncua Subscription per distinct
        # PublishingInterval; per-tier nodeId -> server-side MonitoredItem handle.
        self._subs_by_publish: dict[int, Any] = {}
        self._monitored: dict[int, dict[str, int]] = {}
        # Captured during _pre_connect from the chosen EndpointDescription;
        # used to compose the wrapper-cast i3X namespace URI for this connection.
        self._application_uri: str | None = None
        self._application_name: str | None = None
        # Two-way wire ↔ raw NodeId index, refreshed at apply_snapshot time
        # from BrowseResult.nodes. Routes pass wire-side IDs in (display
        # paths for opaque NodeIds); the binding converts to raw OPC UA
        # NodeIds before talking to asyncua, and converts back when
        # delivering samples so they match the registry's wire-keyed
        # elementIds.
        self._wire_by_raw: dict[str, str] = {}
        self._raw_by_wire: dict[str, str] = {}

    async def start(self) -> None:
        await self.conn.start()

    async def stop(self) -> None:
        await self.conn.stop()

    async def _pre_connect(self, client: UaClientLike) -> Path | None:
        """Discover endpoints, match against configured policy/mode, resolve
        server cert against the trust list, stash the ApplicationUri for
        CreateSessionRequest, capture ApplicationUri+ApplicationName for the
        wrapper-cast i3X namespace, and return the resolved server cert path
        so `_connect_once` can pass it into `_apply_channel`.
        """
        endpoints = await client.connect_and_get_server_endpoints()
        server_uri, resolved = _resolve_endpoint_and_trust(endpoints, self.cfg)
        client._override_server_uri = server_uri  # type: ignore[attr-defined]
        # Capture ApplicationUri/ApplicationName for the wrapper-cast i3X
        # namespace. We re-pick the matched endpoint so the values are
        # consistent with the SecureChannel we open.
        mode = _MODE_BY_NAME[self.cfg.channel.mode]
        match = pick_matching_endpoint(endpoints, policy=self.cfg.channel.policy, mode=mode)
        if match is not None:
            self._application_uri = match.Server.ApplicationUri or None
            app_name = match.Server.ApplicationName
            self._application_name = (
                getattr(app_name, "Text", None) if app_name is not None else None
            ) or None
        logger.info(
            "opcua endpoint discovered for %s: ApplicationUri=%s policy=%s mode=%s",
            self.cfg.name,
            server_uri,
            self.cfg.channel.policy,
            self.cfg.channel.mode,
        )
        return resolved

    async def _discover_max_parents_per_batch(self, client: UaClientLike) -> int:
        """Read the server's published browse-related capabilities and pick a
        safe batch size for `_browse_instances`.

        Standard NodeIds (OPC UA Part 5):
          - `Server.ServerCapabilities.MaxBrowseContinuationPoints` i=2735
            (UInt16) — max simultaneous CPs the server will hand out.
          - `Server.ServerCapabilities.OperationLimits.MaxNodesPerBrowse`
            i=11488 (UInt32) — max nodes per BrowseRequest.

        We size each batch as the smaller of the two (capped to a sane
        ceiling) so we never demand more concurrent CPs than the server
        can give us — exceeding it causes the server to truncate
        high-fan-out folders with ``BadNoContinuationPoints``.

        Either attribute may be missing or zero on older servers; in that
        case we fall back to `MAX_PARENTS_PER_BATCH_DEFAULT`.
        """
        from i3xua.adapters.asyncua.browse import MAX_PARENTS_PER_BATCH_DEFAULT

        async def _read_uint(node_id: ua.NodeId) -> int | None:
            try:
                value = await client.get_node(node_id).read_value()  # type: ignore[attr-defined]
                return int(value) if value is not None else None
            except Exception as exc:
                logger.debug("could not read %s on %s: %s", node_id, self.cfg.name, exc)
                return None

        max_cps = await _read_uint(ua.NodeId(2735, 0))
        max_browse = await _read_uint(ua.NodeId(11488, 0))

        candidates = [v for v in (max_cps, max_browse) if v and v > 0]
        if not candidates:
            chosen = MAX_PARENTS_PER_BATCH_DEFAULT
            logger.info(
                "browse limits not exposed by %s; using default max_parents_per_batch=%d",
                self.cfg.name,
                chosen,
            )
        else:
            # Cap at MAX_PARENTS_PER_BATCH_DEFAULT to keep per-RPC payloads sane
            # even if a server claims arbitrarily large limits.
            chosen = max(1, min(min(candidates), MAX_PARENTS_PER_BATCH_DEFAULT))
            logger.info(
                "browse limits for %s: MaxBrowseContinuationPoints=%s, "
                "MaxNodesPerBrowse=%s → max_parents_per_batch=%d",
                self.cfg.name,
                max_cps,
                max_browse,
                chosen,
            )
        return chosen

    async def _on_connected(self, client: UaClientLike) -> None:
        logger.info("opcua connected: %s", self.cfg.name)
        # Read the server's published browse limits BEFORE we start walking.
        # Picking too high a batch size triggers ``BadNoContinuationPoints``
        # on tag-heavy servers and silently drops high-fan-out folders.
        max_parents = await self._discover_max_parents_per_batch(client)
        # Run a browse, then ship the results to the main loop's registries.
        # Phase timings (seconds) are recorded to surface startup performance
        # via /admin/state — useful when comparing a Reference Server (~7k
        # nodes) against a real PLC/OPC server (varies wildly).
        started_at = datetime.now(UTC)
        t_total = time.monotonic()
        source = _AsyncuaBrowseSource(client)
        source.application_uri = self._application_uri
        source.application_name = self._application_name
        cfg = BrowseConfig(
            namespace_allowlist=tuple(self.cfg.namespace_allowlist)
            if self.cfg.namespace_allowlist
            else (),
            max_parents_per_batch=min(max_parents, self.cfg.max_parents_per_batch),
            max_children_per_batch=self.cfg.max_children_per_batch,
            browse_variable_properties=self.cfg.browse_variable_properties,
        )
        try:
            t_browse = time.monotonic()
            result = await browse(source, connection=self.cfg.name, cfg=cfg)
            browse_s = time.monotonic() - t_browse
        except Exception as exc:
            logger.exception("initial browse failed for %s: %s", self.cfg.name, exc)
            return

        # + reflect custom types two ways so we don't lose anything
        # asyncua's codegen couldn't handle.
        #
        # (a) `_enumerate_generated_types` walks `ua.__dict__` for classes
        # asyncua successfully produced via `load_data_type_definitions`.
        # (b) `_walk_server_structure_types` reads `DataTypeDefinition` directly
        # from every server Structure DataType node — no code-gen, just
        # attribute reads. This catches types (e.g. those referencing the
        # abstract `Enumeration` base) where asyncua's generator bailed.
        #
        # Duplicates across the two passes are coalesced by `structural_hash`
        # when the TypeRegistry reconciles, so we can safely union them.
        # browse() guarantees ns=0 is always first in result.namespaces
        # (UA_CORE_NAMESPACE_URI). default_ns is therefore the OPC UA core URI.
        default_ns = result.namespaces[0].uri if result.namespaces else ""

        t_types = time.monotonic()
        codegen_types = _enumerate_generated_types(
            connection=self.cfg.name, default_namespace_uri=default_ns
        )
        walked_types: list[TypeDescriptor] = []
        try:
            walked_types = await _walk_server_structure_types(
                client, connection=self.cfg.name, default_namespace_uri=default_ns
            )
        except Exception as exc:
            logger.warning(
                "server-side DataTypeDefinition walk failed for %s: %s "
                "(continuing with codegen types only)",
                self.cfg.name,
                exc,
            )
        types_s = time.monotonic() - t_types

        # Dedup by (connection, source_node_id) so codegen wins when both paths
        # surface the same type with identical fields.
        by_source: dict[str, TypeDescriptor] = {}
        for t in (*walked_types, *codegen_types):
            by_source[t.source_node_id] = t
        custom_types = list(by_source.values())

        # `custom_types` come from `_enumerate_generated_types` via
        # asyncua's `load_data_type_definitions` — a separate path from
        # `_browse_types`, so they don't get the `application_uri` stamp
        # that `browse()` applies. Stamp them here so all merged types
        # carry the wrapper-cast namespaceUri ingredient.
        from dataclasses import replace as _dc_replace

        if self._application_uri is not None:
            custom_types = [
                _dc_replace(t, application_uri=self._application_uri) for t in custom_types
            ]
        merged_types = tuple(result.types) + tuple(custom_types)
        enriched = result.__class__(
            namespaces=result.namespaces,
            types=merged_types,
            nodes=result.nodes,
        )

        namespaces = [
            NamespaceInfo(uri=n.uri, connection=self.cfg.name, display_name=n.display_name)
            for n in enriched.namespaces
        ]
        # Refresh the wire ↔ raw NodeId index for this connection. Used
        # by `read_values` (wire → raw) and `deliver_sample` (raw → wire).
        self._wire_by_raw = {n.node_id: (n.wire_node_id or n.node_id) for n in enriched.nodes}
        self._raw_by_wire = {wire: raw for raw, wire in self._wire_by_raw.items()}
        t_snapshot = time.monotonic()
        await self._ship_to_main(
            self.registries.apply_snapshot(
                self.cfg.name,
                namespaces,
                enriched,
                application_uri=self._application_uri,
            )
        )
        snapshot_s = time.monotonic() - t_snapshot
        total_s = time.monotonic() - t_total

        # Stash + emit. The metrics dict is shared with AppState.browse_metrics
        # so /admin/state and the andon UI can render the latest run.
        completed_at = datetime.now(UTC)
        metrics: dict[str, Any] = {
            "started_at": started_at.isoformat(),
            "completed_at": completed_at.isoformat(),
            "browse_s": round(browse_s, 3),
            "types_s": round(types_s, 3),
            "snapshot_s": round(snapshot_s, 3),
            "total_s": round(total_s, 3),
            "namespaces": len(namespaces),
            "types": len(enriched.types),
            "instances": len(enriched.nodes),
        }
        # Keys from as_metrics() must stay in sync with the log line below.
        metrics.update(source.counters.as_metrics())
        self.registries.browse_metrics[self.cfg.name] = metrics
        logger.info(
            "browse complete: %s — %d ns / %d types / %d instances "
            "in %.2fs (browse %.2fs, types %.2fs, snapshot %.2fs); "
            "browse_next_starved=%d (out of %d calls), "
            "browse_initial_starved=%d (recovered=%d, unrecoverable=%d)",
            self.cfg.name,
            metrics["namespaces"],
            metrics["types"],
            metrics["instances"],
            total_s,
            browse_s,
            types_s,
            snapshot_s,
            metrics["browse_next_starved"],
            metrics["browse_next_calls"],
            metrics["browse_initial_starved"],
            metrics["browse_initial_starved_recovered"],
            metrics["browse_initial_starved_unrecoverable"],
        )

        # restore i3X-requested subscriptions now that the registries
        # reflect the (possibly drifted) address space. SubscriptionManager is
        # the authoritative source for what clients want; our local
        # `_monitored` bookkeeping is cleared on disconnect and rebuilt here.
        wanted = await self._ship_to_main(self.registries.wanted_node_ids(self.cfg.name))
        if wanted:
            logger.info(
                "restoring %d monitored items on %s after (re)connect",
                len(wanted),
                self.cfg.name,
            )
            await self.add_monitored(
                list(wanted),
                publishing_ms=self.cfg.default_publishing_interval_ms,
                sampling_ms=self.cfg.default_sampling_interval_ms,
            )

    async def _on_disconnected(self, exc: Exception | None) -> None:
        """session dropped. Drop local subscription bookkeeping so the next
        `_on_connected` creates a fresh asyncua Subscription and re-subscribes
        every element still present in `SubscriptionManager.elements`."""
        _ = exc
        self._subs_by_publish.clear()
        self._monitored.clear()

    async def _ship_to_main(self, coro: Any) -> Any:
        future = asyncio.run_coroutine_threadsafe(coro, self.main_loop)
        return await asyncio.wrap_future(future)

    async def read_values(self, node_ids: list[str]) -> list[ValueSample]:
        # Inputs may be wire-side IDs (display paths for opaque NodeIds);
        # convert to raw OPC UA NodeIds before reading, and translate the
        # resulting samples back to wire-side elementIds.
        node_ids = [self._raw_by_wire.get(nid, nid) for nid in node_ids]
        client = self.conn.client
        samples: list[ValueSample] = []
        for nid in node_ids:
            wire_nid = self._wire_by_raw.get(nid, nid)
            try:
                node = client.get_node(_ua_node_id(nid))  # type: ignore[attr-defined]
                dv = await node.read_data_value()
                neutral = from_ua_data_value(dv)
                samples.append(
                    sample_from_ouajson_data_value(
                        connection=self.cfg.name, node_id=wire_nid, data_value=neutral
                    )
                )
            except Exception as exc:
                logger.debug("read_values(%s!%s) failed: %s", self.cfg.name, nid, exc)
                samples.append(
                    ValueSample(
                        element_id=ElementRef(self.cfg.name, wire_nid).as_id(),
                        value=None,
                        quality=Quality.Bad,
                        timestamp="",
                    )
                )
        return samples

    async def _ensure_subscription(self, publishing_ms: int) -> Any:
        """one asyncua Subscription per distinct PublishingInterval.

        Sampling interval is per-MonitoredItem (see `add_monitored`), so all
        items at a given publishing interval share the same Subscription.
        """
        sub = self._subs_by_publish.get(publishing_ms)
        if sub is not None:
            return sub
        handler = _Handler(self)
        sub = await self.conn.client.create_subscription(publishing_ms, handler)  # type: ignore[attr-defined]
        self._subs_by_publish[publishing_ms] = sub
        return sub

    async def add_monitored(
        self, node_ids: list[str], *, publishing_ms: int, sampling_ms: int
    ) -> None:
        """subscribe each NodeId at the requested (pub, samp) tier.

        A single NodeId may end up with MonitoredItems on multiple tiers if
        different i3X registers ask for different intervals — we track each
        (nid, pub) combination separately so independent unregisters tear
        down only their own item.

        Inputs are wire-side IDs (display paths for opaque NodeIds);
        translated to raw OPC UA NodeIds before the asyncua call.
        """
        node_ids = [self._raw_by_wire.get(nid, nid) for nid in node_ids]
        sub = await self._ensure_subscription(publishing_ms)
        # Already-monitored nodes at THIS publishing tier are skipped — their
        # MonitoredItem already exists. Different publishing tiers get distinct
        # MonitoredItems even for the same NodeId.
        existing_for_pub = self._monitored.get(publishing_ms, {})
        new_ids = [nid for nid in node_ids if nid not in existing_for_pub]
        if not new_ids:
            return
        nodes = [self.conn.client.get_node(_ua_node_id(nid)) for nid in new_ids]  # type: ignore[attr-defined]
        from asyncua import ua  # local import keeps adapter the only asyncua importer

        params = ua.MonitoringParameters()
        params.SamplingInterval = float(sampling_ms)
        handles = await sub.subscribe_data_change(
            nodes, queuesize=0, sampling_interval=float(sampling_ms)
        )
        if not isinstance(handles, list):
            handles = [handles]
        bucket = self._monitored.setdefault(publishing_ms, {})
        for nid, h in zip(new_ids, handles, strict=False):
            bucket[nid] = int(h) if isinstance(h, int) else 0
        _ = params  # asyncua's high-level API takes sampling_interval directly

    async def remove_monitored(self, node_ids: list[str], *, publishing_ms: int) -> None:
        # Inputs are wire-side IDs; translate to raw before unsubscribing.
        node_ids = [self._raw_by_wire.get(nid, nid) for nid in node_ids]
        sub = self._subs_by_publish.get(publishing_ms)
        if sub is None:
            return
        bucket = self._monitored.get(publishing_ms)
        if not bucket:
            return
        drop: list[int] = []
        for nid in node_ids:
            h = bucket.pop(nid, None)
            if h is not None:
                drop.append(h)
        if drop:
            try:
                await sub.unsubscribe(drop)
            except Exception as exc:
                logger.debug("unsubscribe failed: %s", exc)
        # If this tier is now empty, tear down the Subscription itself.
        if not bucket:
            self._monitored.pop(publishing_ms, None)
            try:
                await sub.delete()
            except Exception as exc:
                logger.debug("delete subscription tier %d failed: %s", publishing_ms, exc)
            self._subs_by_publish.pop(publishing_ms, None)

    async def deliver_sample(self, node_id: str, data_value: OUaDataValue) -> None:
        """Called from the asyncua handler thread (via _Handler). Forwards the
        encoded sample to the main-loop SubscriptionManager + HistoryStore.
        `node_id` from asyncua is RAW; we translate to wire form so the
        emitted `element_id` matches the registry's wire-keyed entries.
        """
        wire_nid = self._wire_by_raw.get(node_id, node_id)
        sample = sample_from_ouajson_data_value(
            connection=self.cfg.name, node_id=wire_nid, data_value=data_value
        )
        logger.debug(
            "deliver_sample: element_id=%s quality=%s", sample.element_id, sample.quality
        )
        try:
            await self._ship_to_main(self.registries.fan_out(sample))
        except Exception as exc:
            logger.exception("fan_out failed: %s", exc)


class _Handler:
    """asyncua Subscription handler. Lives on the connection thread; its
    `datachange_notification` method is called synchronously by asyncua."""

    def __init__(self, binding: _ConnectionBinding) -> None:
        self._binding = binding
        self._pending: set[asyncio.Task[None]] = set()

    def datachange_notification(self, node: Any, val: Any, data: DataChangeNotif) -> None:
        _ = val
        try:
            node_id_str = node.nodeid.to_string()
            logger.debug("datachange_notification: node=%s val=%r", node_id_str, val)
            dv = data.monitored_item.Value
            neutral = from_ua_data_value(dv)
            loop = asyncio.get_event_loop()
            task = loop.create_task(self._binding.deliver_sample(node_id_str, neutral))
            self._pending.add(task)
            task.add_done_callback(self._pending.discard)
        except Exception as exc:
            logger.exception("datachange_notification failed: %s", exc)

    def status_change_notification(self, status: Any) -> None:
        """asyncua calls this when the Subscription's server-side status changes
        (e.g. BadTimeout after session drop, or StatusChangeNotification from a
        server restart). Log it so it's visible; the actual recovery is driven
        by `connection_lost_callback` → reconnect loop → subscription restoration."""
        logger.warning(
            "subscription status changed on %s: %s (recovery handled by reconnect loop)",
            self._binding.cfg.name,
            status,
        )


