"""Production `UpstreamDataSource` backed by `asyncua.Client`.

Design:
 - Each configured connection gets its own worker thread running an asyncio
   event loop. The `asyncua.Client` lives on that loop.
 - Every API-side call (`read_values`, `add_monitored_items`, ...) is bridged
   to the target thread via `ThreadPool.run_on`; results come back on the API
   loop.
 - After a successful connect, the binding runs an initial browse + type
   reflection and pushes the snapshot to the main-loop registries via
   `asyncio.run_coroutine_threadsafe`.

OPC UA-SIDE SUBSCRIPTIONS ARE MANDATORY.
We DO NOT poll the OPC UA server for value changes. Every i3X subscription
registration cascades to an asyncua `Subscription.subscribe_data_change(...)`
creating a real OPC UA MonitoredItem on the server. Server-side publishing
interval comes from `connections[*].subscriptions[*].publishing_interval_ms`;
sampling interval is forwarded per MonitoredItem so the server controls how
often it samples each node.

Samples flow: asyncua `datachange_notification(node, val, data)` (sync callback
on the connection thread) -> `_Handler.datachange_notification` -> task that
calls `_ConnectionBinding.deliver_sample` -> Part-6 encode via
`from_ua_data_value` + `sample_from_ouajson_data_value` -> cross-loop bridge to
the main loop's `SubscriptionManager.push` + `HistoryStore.append`.

Everything related to the live OPC UA wire lives here so `core/` and `api/`
remain framework-neutral.
"""

