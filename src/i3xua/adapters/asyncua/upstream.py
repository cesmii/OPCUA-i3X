class AsyncuaUpstreamDataSource:
    """Top-level `UpstreamDataSource` implementation backed by asyncua.

    Construction is two-step so it can be handed to `build_state()` before
    the state's registries exist: call `bind_registries(...)` once the state
    has been built, then `await start()`.
    """

    def __init__(self, config: AppConfig) -> None:
        self._config = config
        self._pool = ThreadPool()
        self._registries: _Registries | None = None
        self._bindings: dict[str, _ConnectionBinding] = {}
        self._started = False

    def bind_registries(
        self,
        *,
        namespaces: NamespaceRegistry,
        types: TypeRegistry,
        instances: InstanceRegistry,
        subscriptions: SubscriptionManager,
        history: HistoryStore,
        browse_metrics: dict[str, dict[str, Any]] | None = None,
    ) -> None:
        self._registries = _Registries(
            namespaces=namespaces,
            types=types,
            instances=instances,
            subscriptions=subscriptions,
            history=history,
            browse_metrics=browse_metrics,
        )

    async def start(self) -> None:
        if self._started:
            return
        if self._registries is None:
            raise RuntimeError("bind_registries() must be called before start()")
        main_loop = asyncio.get_running_loop()
        for cfg in self._config.connections:
            binding = _ConnectionBinding(cfg, self._pool, main_loop, self._registries)
            self._bindings[cfg.name] = binding
            await self._pool.run_on(cfg.name, binding.start)
        self._started = True

    async def stop(self) -> None:
        if not self._started:
            return
        for name, binding in list(self._bindings.items()):
            try:
                await self._pool.run_on(binding.cfg.name, binding.stop)
            except Exception as exc:
                logger.debug("stop() for %s failed: %s", name, exc)
        await self._pool.stop()
        self._started = False

    # ------------------------------------------------------------------ Port impl

    async def list_connections(self) -> list[ConnectionId]:
        return [ConnectionId(name) for name in self._bindings]

    async def browse(self, connection: ConnectionId) -> BrowseResult:
        # The registries are the source of truth after initial browse.
        # A fresh browse is triggered via /admin/refresh which re-runs `_on_connected`.
        raise NotImplementedError("use /admin/refresh to re-browse")

    async def read_values(
        self, connection: ConnectionId, node_ids: Iterable[str]
    ) -> list[ValueSample]:
        binding = self._bindings[connection.name]
        ids = list(node_ids)
        return await self._pool.run_on(binding.cfg.name, lambda: binding.read_values(ids))

    async def add_monitored_items(
        self,
        handle: SubscriptionHandle,
        node_ids: Iterable[str],
        *,
        publishing_ms: int | None = None,
        sampling_ms: int | None = None,
    ) -> None:
        """dispatch to the (publishing_ms) tier on the target connection.

        When intervals aren't given (which is the path the i3X register route
        takes today), the connection's `default_*_interval_ms` from config
        applies. A non-default tier is created on demand by `_ensure_subscription`.
        """
        binding = self._bindings[handle.connection]
        ids = list(node_ids)
        pub = publishing_ms or binding.cfg.default_publishing_interval_ms
        samp = sampling_ms or binding.cfg.default_sampling_interval_ms
        await self._pool.run_on(
            binding.cfg.name,
            lambda: binding.add_monitored(ids, publishing_ms=pub, sampling_ms=samp),
        )

    async def remove_monitored_items(
        self,
        handle: SubscriptionHandle,
        node_ids: Iterable[str],
        *,
        publishing_ms: int | None = None,
    ) -> None:
        binding = self._bindings[handle.connection]
        ids = list(node_ids)
        pub = publishing_ms or binding.cfg.default_publishing_interval_ms
        await self._pool.run_on(
            binding.cfg.name,
            lambda: binding.remove_monitored(ids, publishing_ms=pub),
        )

    def stream(self, handle: SubscriptionHandle) -> Any:
        # Streaming is funneled through the i3X SubscriptionManager; this
        # placeholder is only present because the Protocol requires it.
        _ = handle

        async def _empty() -> Any:
            # Empty async generator: looping over `[]` makes this a generator
            # without unreachable-yield warnings from static analyzers.
            for _ in ():  # pragma: no cover
                yield  # pragma: no cover

        return _empty()


